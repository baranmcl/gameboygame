"""make_font.py — Generate assets/font.png from a hardcoded 8x8 bitmap font.

Output: 128x32 indexed-color PNG with the DMG 4-color palette, glyphs for
ASCII 0x20..0x5F arranged in 16 columns x 4 rows (row-major). Used by
Phase 2 of the foundation plan to provide font tiles for the render
subsystem.

Font data: font8x8 BASIC variant (public domain, derived from FreeBSD
8x8 console font). Each glyph is 8 bytes (rows top to bottom).
LSB = leftmost pixel within each row byte.

This script exists because Phase 2's plan calls for a hand-pixeled
font.png, but generating it programmatically keeps the asset
reproducible and avoids a build-time dependency on pixel-art tooling.

Usage: python tools/make_font.py [output_path]
       (default output: assets/font.png)
"""

